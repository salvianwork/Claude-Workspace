"""Build the run's HyperFrames composition: 04-video/hf/ = one video from shots.json + the voice.

    python -m tools.hf.build <run_dir> [--no-check]

Writes 04-video/hf/index.html (one composition: scenes back to back, each ceil(duration_s x 30)
frames from the voice manifest; transitions inside scene time; captions from words.json;
presenter with mouth data from the scene's wav), data.json (everything the page plays, also
inlined in index.html), kit/ (hf-kit vendor + src + the props the video uses). Hero scenes with
`new_prop: true` load the animator's 04-video/hf/scenes/scene-<id>.js; other heroes load
kit/props/<prop>/prop.js. The build validates shots.json first (not the 2-4 hero count: that is
`python -m tools.hf.shots validate`), then runs `hyperframes check`; a scene that fails to load,
mount or update is reported as `scene-<id>` and the build fails.
"""
from __future__ import annotations

import argparse
import html
import json
import os
import re
import sys
from pathlib import Path

import soundfile as sf

from tools.hf.render import KIT_DIR, HFError, assert_offline, check, install_kit
from tools.hf.shots import FPS, ShotsError, load_run, module_path, review_shots, scene_frames
from tools.voice.mouth import mouth_envelope

_WORD_KEYS = ("i", "text", "display", "start", "end")

_PAGE = """<!doctype html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=1920, height=1080">
  <!-- Generated by `python -m tools.hf.build` from 03-design/shots.json and 02-voice/. Do not
       edit: change shots.json (or the hero modules in scenes/) and build again. -->
  <title>{title}</title>
  <link rel="stylesheet" href="kit/vendor/fonts/fonts.css">
  <style>
    html, body {{ margin: 0; width: 1920px; height: 1080px; overflow: hidden; background: {background}; }}
    #root {{ position: relative; width: 1920px; height: 1080px; overflow: hidden; }}
    .scene {{ position: absolute; left: 0; top: 0; width: 1920px; height: 1080px; overflow: hidden; }}
  </style>
  <script>
    /* A prop or hero module that throws while loading names its scene (hyperframes check
       counts console errors). */
    (function () {{
      var files = {files};
      window.addEventListener("error", function (e) {{
        var f = e.filename || (e.target && e.target.src) || "";
        for (var k in files) {{
          if (f.slice(-k.length) === k) {{
            console.error(files[k].map(function (id) {{ return "scene-" + id; }}).join(", ") + ": " + k +
              " failed to load: " + (e.message || "file missing"));
            return;
          }}
        }}
      }}, true);
    }})();
  </script>
{scripts}
  <script id="hf-data" type="application/json">{data}</script>
</head>
<body>
  <div id="root" data-composition-id="main" data-start="0" data-duration="{total}" data-width="1920" data-height="1080">
{clips}
  </div>
  <script>
    var video = HFKit.mountComposition(JSON.parse(document.getElementById("hf-data").textContent));
    window.__timelines = window.__timelines || {{}};
    window.__timelines["main"] = video.timeline;
  </script>
</body>
</html>
"""


def _num(x: float) -> str:
    return f"{x:.6f}".rstrip("0").rstrip(".")


def _scene_mouth(run_dir: Path, file: str, frames: int, sid: int) -> list[float]:
    wav = run_dir / "02-voice" / file
    if not wav.is_file():
        raise HFError(f"scene {sid}: voice file missing ({wav})")
    samples, sr = sf.read(str(wav), dtype="float32")
    return mouth_envelope(samples, sr, frames, FPS)


def compose_data(run_dir: Path, d: dict, warnings: list[str]) -> dict:
    """The data.json the composition plays (scenes in voice-manifest order)."""
    shots = {s["id"]: s for s in d["shots"]["scenes"]}
    words = {int(s["id"]): s["words"] for s in d["words"]["scenes"]}
    style = d["style"] or {}
    scenes, start = [], 0
    order = [m for m in d["manifest"]["scenes"]]
    for n, m in enumerate(order):
        sid = int(m["id"])
        s = shots[sid]
        frames = scene_frames(m["duration_s"])
        nxt = shots[int(order[n + 1]["id"])].get("transition", "fade") if n + 1 < len(order) else None
        scene = {"id": sid, "kind": s["kind"], "start": start / FPS, "frames": frames, "duration": frames / FPS,
                 "words": [{k: w[k] for k in _WORD_KEYS if k in w} for w in words[sid]],
                 "cues": s.get("cues", []), "camera": s.get("camera", []),
                 "presenter": s.get("presenter") or {"position": "none", "size": "small"},
                 "transition": s.get("transition", "fade"), "next": nxt,
                 "mouth": _scene_mouth(run_dir, m["file"], frames, sid)}
        if s["kind"] == "hero":
            scene.update(prop=s["prop"], new_prop=bool(s.get("new_prop", False)), params=s.get("params", {}))
        else:
            scene.update(scene=s["scene"], props=s["props"])
        scenes.append(scene)
        start += frames
    return {"fps": FPS, "width": 1920, "height": 1080, "frames": start, "total": start / FPS,
            "style": {k: style[k] for k in ("colors", "fonts", "sizes", "safe") if k in style} or None,
            "presenterOutfit": style.get("presenterOutfit", "blazer"),
            "warnings": warnings, "scenes": scenes}


def page(data: dict, title: str, kit_scripts: list[str]) -> tuple[str, list[str]]:
    """(index.html text, prop names copied into kit/props)."""
    files: dict[str, list[int]] = {}
    props: list[str] = []
    for s in data["scenes"]:
        if s["kind"] != "hero":
            continue
        if s["new_prop"]:
            src = f"scenes/scene-{s['id']}.js"
        else:
            src = f"kit/props/{s['prop']}/prop.js"
            if s["prop"] not in props:
                props.append(s["prop"])
        files.setdefault(src, []).append(s["id"])
    srcs = ["kit/vendor/gsap.min.js"] + [f"kit/{p}" for p in kit_scripts] + list(files)
    scripts = "\n".join(f'  <script src="{html.escape(p)}"></script>' for p in srcs)
    clips = "\n".join(
        f'    <div id="scene-{s["id"]}" class="scene clip" data-start="{_num(s["start"])}" '
        f'data-duration="{_num(s["duration"])}" data-track-index="0"></div>' for s in data["scenes"])
    background = ((data.get("style") or {}).get("colors") or {}).get("background", "#0F172A")
    text = _PAGE.format(title=html.escape(title), background=html.escape(background),
                        files=json.dumps(files), scripts=scripts, clips=clips, total=_num(data["total"]),
                        data=json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/"))
    return text, props


def _kit_scripts(kit_dir: Path) -> list[str]:
    """HFKit.SCRIPTS from kit.js (the load order), without running node."""
    src = (Path(kit_dir) / "src" / "kit.js").read_text(encoding="utf-8")
    block = re.search(r"var SCRIPTS = \[(.*?)\];", src, re.S)
    if not block:
        raise HFError("hf-kit/src/kit.js has no SCRIPTS list")
    return re.findall(r'"([^"]+\.js)"', block.group(1))


def _write(path: Path, text: str) -> None:
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def build(run_dir: Path, kit_dir: Path = KIT_DIR, *, run_check: bool = True) -> Path:
    """Build 04-video/hf/ and return that folder (the composition dir for tools.hf.render).

    Raises HFError when shots.json is invalid (every problem listed), the composition would
    load anything from the network, or `hyperframes check` finds errors (a failing scene is
    named `scene-<id>`). Camera warnings are printed and kept in data.json `warnings`."""
    run_dir = Path(run_dir)
    kit_dir = Path(kit_dir)
    comp = run_dir / "04-video" / "hf"
    try:
        d = load_run(run_dir)
        errs, warns = review_shots(d["shots"], d["words"], d["manifest"], kit_dir / "props",
                                   scenes_dir=comp / "scenes", style=d["style"], hero_count=False,
                                   kit_dir=kit_dir)
    except ShotsError as e:
        raise HFError(str(e)) from e
    if errs:
        raise HFError(f"shots.json has {len(errs)} problem(s):\n" + "\n".join(f"- {e}" for e in errs))
    for w in warns:
        print(f"warning: {w}", file=sys.stderr)
    data = compose_data(run_dir, d, warns)
    comp.mkdir(parents=True, exist_ok=True)
    text, props = page(data, f"{run_dir.name} video", _kit_scripts(kit_dir))
    install_kit(comp, kit_dir=kit_dir, props=props)
    for s in data["scenes"]:
        if s["kind"] == "hero" and s["new_prop"] and not module_path(comp / "scenes", s["id"]).is_file():
            raise HFError(f"scene {s['id']}: hero module scenes/scene-{s['id']}.js missing")
    _write(comp / "data.json", json.dumps(data, indent=1, ensure_ascii=False))
    _write(comp / "index.html", text)
    remote = assert_offline(comp)
    if remote:
        raise HFError("the composition would load from the network:\n" + "\n".join(remote))
    if run_check:
        check(comp)
    return comp


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m tools.hf.build", description=__doc__.splitlines()[0])
    p.add_argument("run_dir", type=Path)
    p.add_argument("--no-check", action="store_true", help="skip `hyperframes check` (faster, for drafts)")
    a = p.parse_args(argv)
    try:
        comp = build(a.run_dir, run_check=not a.no_check)
    except HFError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    print(f"composition written: {comp / 'index.html'}" + ("" if a.no_check else " (hyperframes check clean)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
